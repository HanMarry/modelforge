#!/usr/bin/env node
/**
 * Vendors the permissively licensed paper templates used by the math-paper skill.
 *
 * Every source below was checked against the GitHub API (or the upstream README for
 * LPPL) before being added here. Re-running refreshes the files in place; the
 * upstream LICENSE is always fetched alongside the sources so attribution stays
 * verbatim.
 *
 * Deliberately NOT vendored:
 *   - sikouhjw/MathorCupmodeling — repository has no LICENSE file
 *   - latexstudio/mcmthesis       — only mcmthesis.dtx is published; mcmthesis.cls is
 *                                   generated by running xetex over the source, which
 *                                   cannot be reproduced without the author's build
 *
 * Usage: node scripts/vendor-paper-templates.js
 */
const fs = require('fs');
const path = require('path');

const TEMPLATES = path.join(
  __dirname,
  '..',
  '..',
  '..',
  'crates',
  'goose',
  'src',
  'skills',
  'builtins',
  'math_paper',
  'assets',
  'templates'
);

/** repo + branch + files to mirror, per destination directory. */
const SOURCES = [
  {
    directory: 'jxust-latex',
    repo: 'sikouhjw/JXUSTmodeling',
    branch: 'master',
    license: 'MIT',
    upstream: 'https://github.com/sikouhjw/JXUSTmodeling',
    files: [
      'JXUSTmodeling.cls',
      'main.tex',
      'example.tex',
      'LICENSE',
      'figures/daiquanshuzi.tex',
      'figures/liuchentu.tex',
      'figures/tab.tex',
      'figures/tikz.tex',
    ],
  },
  {
    directory: 'cumcm-latex',
    repo: 'Sustainable-Enjoyment/CUMCM-LaTeX-Template',
    branch: 'main',
    license: 'MIT',
    upstream: 'https://github.com/Sustainable-Enjoyment/CUMCM-LaTeX-Template',
    files: ['cumcmthesis.cls', 'template.tex', 'LICENSE'],
  },
  {
    directory: 'cumcm-typst',
    repo: 'a-kkiri/CUMCM-typst-template',
    branch: 'main',
    license: 'Apache-2.0',
    upstream: 'https://github.com/a-kkiri/CUMCM-typst-template',
    files: ['lib.typ', 'LICENSE'],
  },
];

async function download(repo, branch, file) {
  const url = `https://raw.githubusercontent.com/${repo}/${branch}/${file}`;
  const response = await fetch(url, { headers: { 'User-Agent': 'modelforge-vendor' } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
  return Buffer.from(await response.arrayBuffer());
}

async function main() {
  let written = 0;
  let failed = 0;

  for (const source of SOURCES) {
    const root = path.join(TEMPLATES, source.directory);
    fs.mkdirSync(root, { recursive: true });
    console.log(`\n${source.directory}  (${source.license})  <- ${source.repo}`);

    for (const file of source.files) {
      const target = path.join(root, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      try {
        const body = await download(source.repo, source.branch, file);
        fs.writeFileSync(target, body);
        console.log(`  ok      ${file} (${body.length} bytes)`);
        written++;
      } catch (error) {
        console.error(`  FAILED  ${file}: ${error.message}`);
        failed++;
      }
    }
  }

  console.log(`\n${written} file(s) written, ${failed} failed`);
  if (failed) process.exitCode = 1;
}

if (require.main === module) main();
