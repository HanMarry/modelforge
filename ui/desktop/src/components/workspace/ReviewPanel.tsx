const COMPETITIONS = COMPETITION_CATALOG.competitions;

/** Failures whose `detail` is the model's own text, shown under "Details". */
const REPLY_FAILURES: ReadonlySet<ReviewFailure['kind']> = new Set<ReviewFailure['kind']>([
  'no-json',
  'refused',
  'output-truncated',
  'invalid-output',
]);

